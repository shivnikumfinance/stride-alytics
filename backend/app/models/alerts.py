"""ORM models for alert acknowledgements (migration 009) and weekly picks (migration 005)."""

from __future__ import annotations

from datetime import date, datetime
from uuid import UUID

from sqlalchemy import DECIMAL, Date, ForeignKey, String, TIMESTAMP, Text, text
from sqlalchemy.orm import Mapped, mapped_column

from app.database import Base
from app.models._types import new_uuid, utcnow


class AlertAck(Base):
    __tablename__ = "alert_acks"

    id: Mapped[UUID] = mapped_column(
        primary_key=True, default=new_uuid, server_default=text("gen_random_uuid()")
    )
    user_id: Mapped[UUID] = mapped_column(ForeignKey("users.id"), nullable=False, index=True)
    trade_id: Mapped[UUID] = mapped_column(ForeignKey("trades.id"), nullable=False)
    code: Mapped[str] = mapped_column(String(32), nullable=False)
    severity: Mapped[str] = mapped_column(String(16), nullable=False)
    note: Mapped[str | None] = mapped_column(Text, nullable=True)
    acknowledged_at: Mapped[datetime] = mapped_column(
        TIMESTAMP(timezone=True), default=utcnow, server_default=text("now()"), nullable=False
    )
    resolved_at: Mapped[datetime | None] = mapped_column(TIMESTAMP(timezone=True), nullable=True)


class WeeklyPick(Base):
    """A pick generated by ``scheduler/scripts/generate_picks.py`` (read-only for the app)."""

    __tablename__ = "weekly_picks"

    id: Mapped[UUID] = mapped_column(
        primary_key=True, default=new_uuid, server_default=text("gen_random_uuid()")
    )
    symbol: Mapped[str] = mapped_column(String, nullable=False)
    side: Mapped[str] = mapped_column(String(8), nullable=False)
    strike: Mapped[float | None] = mapped_column(DECIMAL(10, 2), nullable=True)
    expiry: Mapped[date | None] = mapped_column(Date, nullable=True)
    entry_price: Mapped[float] = mapped_column(DECIMAL(10, 4), nullable=False)
    target_price: Mapped[float | None] = mapped_column(DECIMAL(10, 4), nullable=True)
    stop_loss: Mapped[float | None] = mapped_column(DECIMAL(10, 4), nullable=True)
    rationale: Mapped[str] = mapped_column(Text, nullable=False)
    confidence: Mapped[float] = mapped_column(DECIMAL(3, 2), nullable=False)
    week_of: Mapped[date] = mapped_column(Date, nullable=False)
    generated_at: Mapped[datetime] = mapped_column(
        TIMESTAMP(timezone=True), default=utcnow, server_default=text("now()"), nullable=False
    )
    closed_at: Mapped[datetime | None] = mapped_column(TIMESTAMP(timezone=True), nullable=True)
    realized_pnl: Mapped[float | None] = mapped_column(DECIMAL(12, 2), nullable=True)
