import { Badge, Button, Card, PageHeader } from "../components/ui";
import { GateResultPanel } from "../components/gate";
import { useGateCheck, usePicks } from "../hooks/queries";
import type { WeeklyPick } from "../types";
import { fmtUsd } from "../utils";

function PickCard({ pick }: { pick: WeeklyPick }) {
  const gate = useGateCheck();
  const option = pick.side !== "stock";

  return (
    <Card
      title={`${pick.symbol} ${pick.side.toUpperCase()}${pick.strike ? ` ${pick.strike}` : ""}`}
      subtitle={pick.expiry ? `Expires ${pick.expiry}` : undefined}
      actions={<Badge tone="indigo">{Math.round(pick.confidence * 100)}% confidence</Badge>}
    >
      <p className="text-sm text-gray-700">{pick.rationale}</p>
      <dl className="mt-3 grid grid-cols-4 gap-2 text-sm">
        <div>
          <dt className="text-xs text-gray-500">Entry</dt>
          <dd className="font-medium">{pick.entry_price}</dd>
        </div>
        <div>
          <dt className="text-xs text-gray-500">Target</dt>
          <dd className="font-medium text-green-700">{pick.target_price ?? "—"}</dd>
        </div>
        <div>
          <dt className="text-xs text-gray-500">Stop</dt>
          <dd className="font-medium text-red-700">{pick.stop_loss ?? "—"}</dd>
        </div>
        <div>
          <dt className="text-xs text-gray-500">Expected value</dt>
          <dd className={`font-medium ${(pick.ev ?? 0) >= 0 ? "text-green-700" : "text-red-700"}`}>
            {pick.ev === null || pick.ev === undefined ? "—" : fmtUsd(pick.ev)}
          </dd>
        </div>
      </dl>
      <div className="mt-3">
        <Button
          size="sm"
          variant="secondary"
          loading={gate.isPending}
          onClick={() =>
            gate.mutate({
              symbol: pick.symbol,
              trade_type: pick.side,
              strike: option ? pick.strike : null,
              expiry: option ? pick.expiry : null,
            })
          }
        >
          Check gate
        </Button>
      </div>
      {gate.data && (
        <div className="mt-3">
          <GateResultPanel
            clear={gate.data.clear}
            status={gate.data.status}
            reasons={gate.data.reasons}
            notEvaluated={gate.data.not_evaluated}
          />
        </div>
      )}
      {gate.isError && (
        <p role="alert" className="mt-3 text-sm text-red-600">
          Could not check the gate. Try again.
        </p>
      )}
    </Card>
  );
}

export function PicksPage() {
  const picks = usePicks();

  return (
    <div className="space-y-4">
      <PageHeader
        title="Weekly Picks"
        subtitle={
          picks.data?.week_of
            ? `Ideas for the week of ${picks.data.week_of}, best expected value first. Always check the gate before trading.`
            : "Weekly ideas, generated by the scheduler (Sundays 23:00 UTC)."
        }
      />
      {picks.isLoading ? (
        <p className="text-sm text-gray-500">Loading picks…</p>
      ) : picks.isError ? (
        <p role="alert" className="text-sm text-red-600">
          Could not load the picks. Try refreshing.
        </p>
      ) : (picks.data?.data.length ?? 0) === 0 ? (
        <Card>
          <p className="text-sm text-gray-600">
            No picks yet. They appear after the weekly job has run (Sundays 23:00 UTC).
          </p>
        </Card>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 xl:grid-cols-3 gap-4">
          {picks.data?.data.map((p) => (
            <PickCard key={p.id} pick={p} />
          ))}
        </div>
      )}
    </div>
  );
}
